import * as XLSX from 'xlsx'

export interface ReportData {
  title: string
  sheets: SheetData[]
}

export interface SheetData {
  name: string
  headers: string[]
  data: any[][]
}

export const exportToExcel = (reportData: ReportData, filename?: string) => {
  const workbook = XLSX.utils.book_new()
  
  reportData.sheets.forEach((sheet) => {
    const worksheet = XLSX.utils.aoa_to_sheet([sheet.headers, ...sheet.data])
    XLSX.utils.book_append_sheet(workbook, worksheet, sheet.name)
  })
  
  const file = filename || `${reportData.title}_${new Date().toISOString().split('T')[0]}.xlsx`
  XLSX.writeFile(workbook, file)
}

